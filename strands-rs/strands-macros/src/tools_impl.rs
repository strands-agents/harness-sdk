//! `#[tools]` on an `impl` block with `#[tool]` methods.

use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::ext::IdentExt;
use syn::{ImplItem, ImplItemFn, ItemImpl, Path, Visibility};

use crate::attrs::{ToolArgs, ToolsArgs, default_crate, is_tool_attr, parse_args, parse_attr};
use crate::docs::tool_description;
use crate::expand::{ToolDef, tool_items};
use crate::signature::{FnKind, analyze};
use crate::tool_fn::tool_name;

pub(crate) fn expand(args: TokenStream, item: TokenStream) -> TokenStream {
    let mut block: ItemImpl = match syn::parse2(item) {
        Ok(block) => block,
        Err(error) => return error.into_compile_error(),
    };
    let generated = parse_args::<ToolsArgs>(args)
        .map_err(syn::Error::from)
        .and_then(|args| expand_impl(args, &mut block));
    match generated {
        Ok(generated) => quote!(#block #generated),
        Err(error) => {
            let error = error.into_compile_error();
            quote!(#block #error)
        }
    }
}

fn expand_impl(args: ToolsArgs, block: &mut ItemImpl) -> syn::Result<TokenStream> {
    if let Some((path, _)) = &block.trait_ {
        return Err(syn::Error::new_spanned(
            path,
            "`#[tools]` goes on an inherent `impl` block, not a trait impl",
        ));
    }
    if !block.generics.params.is_empty() || block.generics.where_clause.is_some() {
        return Err(syn::Error::new_spanned(
            &block.generics,
            "`#[tools]` impl blocks cannot be generic",
        ));
    }
    let krate = args.krate.unwrap_or_else(default_crate);
    let mut tools = Vec::new();
    let mut errors: Option<syn::Error> = None;
    for item in &mut block.items {
        let ImplItem::Fn(method) = item else {
            continue;
        };
        let Some(index) = method.attrs.iter().position(is_tool_attr) else {
            continue;
        };
        let attr = method.attrs.remove(index);
        match tool_method(&krate, &attr, method) {
            Ok(tool) => tools.push(tool),
            Err(error) => match &mut errors {
                Some(errors) => errors.combine(error),
                None => errors = Some(error),
            },
        }
    }
    if let Some(errors) = errors {
        return Err(errors);
    }
    if tools.is_empty() {
        return Err(syn::Error::new_spanned(
            &block.self_ty,
            "`#[tools]` needs at least one `#[tool]` method",
        ));
    }
    let self_ty = &block.self_ty;
    let constructors = tools.iter().map(|tool| &tool.constructor);
    let items = tools.iter().map(|tool| {
        let ToolMethod {
            def_items,
            constructor,
            vis,
            name,
            ..
        } = tool;
        let doc = format!("The `{name}` tool, generated by `#[tools]`; it calls the method on this value.");
        quote! {
            const _: () = {
                struct __StrandsTool(#krate::__private::Arc<#self_ty>);

                #def_items

                impl #self_ty {
                    #[doc = #doc]
                    #vis fn #constructor(self: &#krate::__private::Arc<Self>) -> impl #krate::Tool {
                        __StrandsTool(#krate::__private::Arc::clone(self))
                    }
                }
            };
        }
    });
    let tools_vis = widest_visibility(tools.iter().map(|tool| &tool.vis));
    Ok(quote! {
        #(#items)*

        impl #self_ty {
            /// The tools of this value's `#[tool]` methods, generated by `#[tools]`.
            #tools_vis fn tools(self: &#krate::__private::Arc<Self>) -> ::std::vec::Vec<#krate::ToolSource> {
                ::std::vec![#(#krate::ToolSource::from(self.#constructors())),*]
            }
        }
    })
}

struct ToolMethod {
    name: String,
    vis: Visibility,
    constructor: syn::Ident,
    def_items: TokenStream,
}

fn tool_method(krate: &Path, attr: &syn::Attribute, method: &mut ImplItemFn) -> syn::Result<ToolMethod> {
    let args: ToolArgs = parse_attr(attr)?;
    if let Some(path) = &args.krate {
        return Err(syn::Error::new_spanned(
            path,
            "set `crate` on `#[tools(crate = \"..\")]`, not on its methods",
        ));
    }
    let signature = analyze(&mut method.sig, FnKind::Method)?;
    let ident = &method.sig.ident;
    let name = tool_name(args.name.as_ref(), ident)?;
    let description = tool_description(args.description.as_ref(), &method.attrs, ident)?;
    let def_items = tool_items(&ToolDef {
        krate,
        name: &name,
        description: &description,
        signature: &signature,
        tool_type: quote!(__StrandsTool),
        callee: quote!(__strands_receiver.#ident),
        setup: quote!(let __strands_receiver = #krate::__private::Arc::clone(&self.0);),
    });
    Ok(ToolMethod {
        name,
        vis: method.vis.clone(),
        constructor: format_ident!("{}_tool", ident.unraw(), span = ident.span()),
        def_items,
    })
}

/// The visibility for `tools()`: the most visible of the tool methods' visibilities.
fn widest_visibility<'a>(visibilities: impl Iterator<Item = &'a Visibility>) -> Visibility {
    let rank = |vis: &Visibility| match vis {
        Visibility::Public(_) => 3,
        Visibility::Restricted(restricted) if restricted.path.is_ident("crate") => 2,
        Visibility::Restricted(_) => 1,
        Visibility::Inherited => 0,
    };
    visibilities
        .fold(None::<&Visibility>, |widest, vis| match widest {
            Some(widest) if rank(widest) >= rank(vis) => Some(widest),
            _ => Some(vis),
        })
        .cloned()
        .unwrap_or(Visibility::Inherited)
}
