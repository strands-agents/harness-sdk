//! `#[tool]` on a free function.

use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::ext::IdentExt;
use syn::{Ident, ItemFn, LitStr};

use crate::attrs::{ToolArgs, default_crate, parse_args};
use crate::docs::{is_valid_tool_name, pascal_case, tool_description};
use crate::expand::{ToolDef, tool_items};
use crate::signature::{FnKind, analyze};

pub(crate) fn expand(args: TokenStream, item: TokenStream) -> TokenStream {
    let mut function: ItemFn = match syn::parse2(item) {
        Ok(function) => function,
        Err(error) => return error.into_compile_error(),
    };
    let generated = parse_args::<ToolArgs>(args)
        .map_err(syn::Error::from)
        .and_then(|args| expand_fn(args, &mut function));
    match generated {
        Ok(generated) => quote!(#function #generated),
        Err(error) => {
            let error = error.into_compile_error();
            quote!(#function #error)
        }
    }
}

fn expand_fn(args: ToolArgs, function: &mut ItemFn) -> syn::Result<TokenStream> {
    let signature = analyze(&mut function.sig, FnKind::Free)?;
    let krate = args.krate.unwrap_or_else(default_crate);
    let fn_ident = &function.sig.ident;
    let name = tool_name(args.name.as_ref(), fn_ident)?;
    let description = tool_description(args.description.as_ref(), &function.attrs, fn_ident)?;
    let struct_ident = format_ident!("{}", pascal_case(&fn_ident.unraw().to_string()), span = fn_ident.span());
    let items = tool_items(&ToolDef {
        krate: &krate,
        name: &name,
        description: &description,
        signature: &signature,
        tool_type: quote!(#struct_ident),
        callee: quote!(#fn_ident),
        setup: TokenStream::new(),
    });
    let doc = format!("The `{name}` tool, generated by `#[tool]` from `{}`.", fn_ident.unraw());
    let vis = &function.vis;
    Ok(quote! {
        #[doc = #doc]
        #[derive(::core::clone::Clone, ::core::marker::Copy, ::core::default::Default, ::core::fmt::Debug)]
        #vis struct #struct_ident;

        const _: () = {
            #items
        };
    })
}

/// The model-facing name: the override, or the function name.
pub(crate) fn tool_name(name: Option<&LitStr>, ident: &Ident) -> syn::Result<String> {
    let (value, span) = name.map_or_else(
        || (ident.unraw().to_string(), ident.span()),
        |name| (name.value(), name.span()),
    );
    if !is_valid_tool_name(&value) {
        return Err(syn::Error::new(
            span,
            format!("tool name `{value}` must be 1 to 64 ASCII letters, digits, `_` or `-`"),
        ));
    }
    Ok(value)
}
