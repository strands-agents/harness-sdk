import { afterEach, describe, expect, it, vi } from 'vitest'
import { Buffer } from 'node:buffer'

import { configureLogging, logger } from '../../src/logging.js'
import { CHECKS, mediaProblem } from '../../src/tools/media-validation.js'
import {
  ANIMATED_GIF,
  ANIMATED_WEBP,
  DOC,
  DOCX,
  GIF,
  HTML,
  JPEG,
  PDF,
  PDF_LINEARIZED_CUT,
  PNG,
  PNG_IDAT,
  PROGRESSIVE_JPEG,
  WEBP,
  XLS,
  XLSX,
  jpeg,
  ole,
  png,
  pngChunk,
  zipArchive,
} from './media-fixtures.js'

const cat = (...parts: (Uint8Array | string | number[])[]): Buffer =>
  Buffer.concat(parts.map((p) => (typeof p === 'string' ? Buffer.from(p, 'latin1') : Buffer.from(p))))
const flip = (data: Buffer, at: number): Buffer => cat(data.subarray(0, at), [data[at]! ^ 0xff], data.subarray(at + 1))

const VALID: [string, Buffer][] = [
  ['png', PNG],
  ['jpeg', JPEG],
  ['jpeg', PROGRESSIVE_JPEG],
  ['gif', GIF],
  ['gif', ANIMATED_GIF],
  ['webp', WEBP],
  ['webp', ANIMATED_WEBP],
  ['pdf', PDF],
  ['docx', DOCX],
  ['xlsx', XLSX],
  ['doc', DOC],
  ['xls', XLS],
]

describe('mediaProblem', () => {
  it.each(VALID)('passes a valid %s file', (format, data) => {
    expect(mediaProblem(format, data)).toBeUndefined()
  })

  // Each of these renders on Bedrock despite the flaw.
  it.each<[string, string, Buffer]>([
    ['png', 'trailing junk', cat(PNG, 'trailing junk')],
    ['png', 'a bad ancillary checksum', png(cat(pngChunk('tEXt', Buffer.from('ab')).subarray(0, -4), [0, 0, 0, 0]))],
    ['jpeg', 'no end marker', JPEG.subarray(0, -2)],
    ['jpeg', 'a baseline cut inside its scan', JPEG.subarray(0, JPEG.indexOf(cat([0xff, 0x00])))],
    ['jpeg', 'fill bytes before a marker', cat(JPEG.subarray(0, 20), Buffer.alloc(100, 0xff), JPEG.subarray(20))],
    ['jpeg', 'a progressive cut inside its second scan', PROGRESSIVE_JPEG.subarray(0, -4)],
    ['gif', 'no trailer', GIF.subarray(0, -1)],
    ['gif', 'a cut inside its second frame', ANIMATED_GIF.subarray(0, -5)],
    ['webp', 'trailing junk', cat(WEBP, 'trailing junk')],
    ['webp', 'a cut inside its second frame', ANIMATED_WEBP.subarray(0, -5)],
    ['pdf', 'junk before the header and no %%EOF', cat('junk\n', PDF.subarray(0, PDF.indexOf('%%EOF')))],
    ['pdf', 'a comment after the trailer', cat(PDF, '\n% generated by obj-tool\n')],
    ['doc', 'a docx container', DOCX],
    ['docx', 'a doc container', DOC],
    ['xls', 'an xlsx container', XLSX],
    ['xlsx', 'an xls container', XLS],
    ['xls', 'a WORKBOOK stream', ole(['WORKBOOK'])],
    ['xls', 'a Book stream', ole(['Book'])],
    ['doc', 'both Word and Excel streams', ole(['WordDocument', 'Workbook'])],
    ['doc', 'unused FAT entries marked free', ole(['WordDocument'], 0xffffffff)],
  ])('passes a renderable %s with %s', (format, _label, data) => {
    expect(mediaProblem(format, data)).toBeUndefined()
  })

  const idatData = PNG_IDAT + 4
  it.each<[string, Buffer, string]>([
    ['png', PNG.subarray(0, PNG.length / 2), 'it is truncated'],
    ['png', PNG.subarray(0, -12), 'it is truncated'],
    ['png', cat(PNG.subarray(0, 8), pngChunk('IEND', Buffer.alloc(0))), 'its IHDR header is malformed'],
    ['png', flip(PNG, idatData), 'a chunk checksum does not match'],
    ['png', cat(PNG.subarray(0, PNG_IDAT - 4), pngChunk('IEND', Buffer.alloc(0))), 'it has no image data'],
    ['jpeg', JPEG.subarray(0, JPEG.indexOf(cat([0xff, 0xda]))), 'it has no image data'],
    ['jpeg', JPEG.subarray(0, 30), 'it is truncated'],
    ['jpeg', cat(JPEG.subarray(0, 2), 'JFIF', JPEG.subarray(2)), 'its marker segments are malformed'],
    ['jpeg', jpeg(0xc4), 'it has no image data'],
    ['jpeg', PROGRESSIVE_JPEG.subarray(0, PROGRESSIVE_JPEG.indexOf(cat([0xff, 0x00]))), 'it has no image data'],
    ['gif', GIF.subarray(0, 10), 'it is truncated'],
    ['gif', GIF.subarray(0, 30), 'it is truncated'],
    ['gif', GIF.subarray(0, 19), 'it has no image data'],
    ['gif', cat(GIF.subarray(0, 19), [0], GIF.subarray(19)), 'its block structure is malformed'],
    ['gif', ANIMATED_GIF.subarray(0, 30), 'it is truncated'],
    ['webp', WEBP.subarray(0, 24), 'it is truncated'],
    ['webp', WEBP.subarray(0, 12), 'it has no image data'],
    ['webp', ANIMATED_WEBP.subarray(0, 60), 'it is truncated'],
    ['pdf', Buffer.alloc(0), 'it has no %PDF- header'],
    ['pdf', HTML, 'it has no %PDF- header'],
    [
      'pdf',
      PDF.subarray(0, PDF.indexOf('startxref')),
      'it does not end with a cross-reference trailer, so it is likely truncated',
    ],
    ['pdf', PDF_LINEARIZED_CUT, 'it does not end with a cross-reference trailer, so it is likely truncated'],
    ['docx', Buffer.alloc(0), 'it is not a Word document'],
    ['xlsx', HTML, 'it is not an Excel workbook'],
    ['docx', DOCX.subarray(0, DOCX.length / 2), 'its zip archive is corrupt or truncated'],
    ['docx', DOCX.subarray(0, -30), 'its zip archive is corrupt or truncated'],
    ['docx', zipArchive('word/document.xml'), 'it is a zip archive, not an Office document'],
    ['docx', XLSX, 'it is not a Word document'],
    ['xlsx', DOCX, 'it is not an Excel workbook'],
    ['doc', DOC.subarray(0, -512), 'it is truncated'],
    ['doc', DOC.subarray(0, 300), 'it is truncated'],
    ['doc', cat(DOC.subarray(0, 30), [10, 0], DOC.subarray(32)), 'its header is malformed'],
    ['doc', ole(['WordDocument'], 2), 'it is truncated'],
    ['xls', DOC, 'it is not an Excel workbook'],
    ['doc', XLS, 'it is not a Word document'],
    ['doc', ole(['worddocument']), 'it is not a Word document'],
    ['xls', ole(['BOOK']), 'it is not an Excel workbook'],
  ])('fails a broken or mislabeled %s with why (case %#)', (format, data, problem) => {
    expect(mediaProblem(format, data)).toBe(problem)
  })

  it('fails a zip whose entry lies outside the archive', () => {
    const central = DOCX.lastIndexOf('PK\x01\x02')
    const pastTheEnd = Buffer.from(DOCX)
    pastTheEnd.writeUInt32LE(DOCX.length, central + 42)
    expect(mediaProblem('docx', pastTheEnd)).toBe('its zip archive is corrupt or truncated')
  })

  it('takes a zip64 archive on structure alone', () => {
    const zip64 = Buffer.from(DOCX)
    zip64.writeUInt32LE(0xffffffff, DOCX.lastIndexOf('PK\x05\x06') + 16)
    expect(mediaProblem('docx', zip64)).toBeUndefined()
  })

  // The shortest prefix that still matches each image signature, which `read` sniffs before any check runs.
  const signatureLength: Record<string, number> = { png: 8, jpeg: 3, gif: 6, webp: 12 }

  it.each(VALID)('judges every prefix of a valid %s file without error', (format, data) => {
    // A check that throws falls back to sending the file unchecked; truncation must be caught, not fallen back on.
    for (let end = signatureLength[format] ?? 0; end < data.length; end++) {
      expect(() => CHECKS[format]!(data.subarray(0, end)), `${format} cut at ${end}`).not.toThrow()
    }
  })

  describe('when a check throws', () => {
    const original = CHECKS.png!
    const originalLogger = logger
    afterEach(() => {
      CHECKS.png = original
      configureLogging(originalLogger)
    })

    it('passes the file and warns', () => {
      const warn = vi.fn()
      configureLogging({ ...logger, warn })
      CHECKS.png = () => {
        throw new RangeError('unexpected layout')
      }
      expect(mediaProblem('png', PNG)).toBeUndefined()
      expect(warn).toHaveBeenCalledWith(
        'mediaFormat=<png> | media validation failed, sending the file unchecked',
        expect.any(RangeError)
      )
    })
  })
})
